"""Pack the web UI into src/web_assets.h as gzip byte arrays.

Runs automatically as a PlatformIO pre-build script (extra_scripts = pre:tools/embed_web.py)
and can also be run by hand:  python tools/embed_web.py

- web/index.html                         -> INDEX_HTML_GZ
- web/vendor/blockly/{blockly,blocks,lua}_compressed.js + msg/th.js
                                         -> BLOCKLY_JS_GZ (one file; empty until phase 2 adds Blockly)
- web/vendor/blockly/media/* (not .mp3)  -> MEDIA[] {name, type, data, len}
The header is only rewritten when its content changes, so builds stay incremental.
"""
import gzip
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "web")
BLOCKLY = os.path.join(WEB, "vendor", "blockly")
OUT = os.path.join(ROOT, "src", "web_assets.h")
BLOCKLY_PARTS = ["blockly_compressed.js", "blocks_compressed.js", "lua_compressed.js", os.path.join("msg", "en.js"), "=SNAPSHOT_EN", os.path.join("msg", "th.js")]
# English messages are kept in window.BLOCKLY_MSG_EN (block text uses them), Thai fills the rest of the UI
SNAPSHOT_EN = b"window.BLOCKLY_MSG_EN = Object.assign({}, Blockly.Msg);\n"
TYPES = {".png": "image/png", ".gif": "image/gif", ".svg": "image/svg+xml", ".cur": "image/x-icon",
         ".jpg": "image/jpeg", ".css": "text/css", ".js": "application/javascript"}


def gz(data):
    return gzip.compress(data, compresslevel=9, mtime=0)


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    body = "\n".join(lines) if data else "  0"
    return (f"static const uint8_t {name}[] PROGMEM = {{\n{body}\n}};\n"
            f"static const size_t {name}_LEN = {len(data)};\n")


def build():
    parts = []
    total = 0

    with open(os.path.join(WEB, "index.html"), "rb") as f:
        index = gz(f.read())
    parts.append(c_array("INDEX_HTML_GZ", index))
    total += len(index)

    blockly_files = [os.path.join(BLOCKLY, p) for p in BLOCKLY_PARTS if not p.startswith("=")]
    has_blockly = all(os.path.isfile(p) for p in blockly_files)
    blockly = b""
    if has_blockly:
        raw = b""
        for p in BLOCKLY_PARTS:
            if p == "=SNAPSHOT_EN":
                raw += SNAPSHOT_EN
                continue
            with open(os.path.join(BLOCKLY, p), "rb") as f:
                src = f.read()
            # drop source-map comments: the .map files are not served
            src = b"\n".join(l for l in src.split(b"\n") if not l.startswith(b"//# sourceMappingURL"))
            raw += src + b"\n;\n"
        blockly = gz(raw)
    parts.append(f"#define HAS_BLOCKLY {1 if has_blockly else 0}\n")
    parts.append(c_array("BLOCKLY_JS_GZ", blockly))
    total += len(blockly)

    media = []
    mdir = os.path.join(BLOCKLY, "media")
    if os.path.isdir(mdir):
        for name in sorted(os.listdir(mdir)):
            ext = os.path.splitext(name)[1].lower()
            if ext not in TYPES:
                continue  # skips .mp3/.ogg/.wav (sounds are disabled)
            with open(os.path.join(mdir, name), "rb") as f:
                data = gz(f.read())
            ident = "MEDIA_%d" % len(media)
            parts.append(c_array(ident, data))
            media.append((name, TYPES[ext], ident))
            total += len(data)

    parts.append("struct MediaFile { const char *name; const char *type; const uint8_t *data; size_t len; };\n")
    if media:
        rows = ",\n".join(f'  {{"{n}", "{t}", {i}, {i}_LEN}}' for n, t, i in media)
        parts.append(f"static const MediaFile MEDIA[] = {{\n{rows}\n}};\n")
    else:
        parts.append('static const MediaFile MEDIA[] = {{"", "", nullptr, 0}};\n')
    parts.append(f"static const size_t MEDIA_COUNT = {len(media)};\n")

    header = ("// Generated by tools/embed_web.py -- do not edit.\n#pragma once\n#include <Arduino.h>\n\n"
              + "\n".join(parts))
    old = None
    if os.path.isfile(OUT):
        with open(OUT, "r", encoding="utf-8") as f:
            old = f.read()
    if old != header:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(header)
        print(f"embed_web: wrote {OUT} ({total} bytes gzip, blockly={'yes' if has_blockly else 'no'}, media={len(media)})")


build()
